#!/usr/bin/env python3
"""Turns the Slotify wordmark (assets/logo-on-dark.webp) into the list of pills the 3D stage assembles at the end of the page.

Each horizontal row of the logo becomes one pill per solid run (a "scanline" cut of the letters). The purple dot of the i is
marked so the stage can paint it with the accent colour. Output: js/gl/wordmark-data.js (run once; the result is committed).

    pip install pillow numpy
    python tools/make-wordmark.py
"""
import sys
from pathlib import Path
import numpy as np
from PIL import Image

ROWS = int(sys.argv[1]) if len(sys.argv) > 1 else 30
root = Path(__file__).resolve().parent.parent
im = Image.open(root / 'assets' / 'logo-on-dark.webp').convert('RGBA')
a = np.array(im).astype(int)
H, W = a.shape[:2]
alpha = a[..., 3]
r, g, b = a[..., 0], a[..., 1], a[..., 2]
solid = alpha > 110
purple = solid & (b - g > 80) & (r < 215)

ys, xs = np.where(solid)
y0, y1 = ys.min(), ys.max() + 1
band = (y1 - y0) / ROWS
min_len = band * 0.8
pills = []
for row in range(ROWS):
    ya, yb = int(round(y0 + row * band)), int(round(y0 + (row + 1) * band))
    yb = max(yb, ya + 1)
    cov = solid[ya:yb].mean(axis=0) >= 0.5
    pur = purple[ya:yb].mean(axis=0) >= 0.4
    x = 0
    runs = []
    while x < W:
        if cov[x]:
            s = x
            while x < W and cov[x]:
                x += 1
            runs.append([s, x])
        else:
            x += 1
    merged = []
    for s, e in runs:                      # close tiny anti-aliasing gaps
        if merged and s - merged[-1][1] < 3:
            merged[-1][1] = e
        else:
            merged.append([s, e])
    for s, e in merged:
        if e - s < min_len:                # never thinner than a round dot
            c = (s + e) / 2
            s, e = c - min_len / 2, c + min_len / 2
        acc = 1 if pur[int(max(0, s)):int(min(W, e))].mean() > 0.35 else 0
        pills.append((row, round(s, 1), round(e, 1), acc))

out = root / 'js' / 'gl' / 'wordmark-data.js'
body = ',\n  '.join('[%d,%s,%s,%d]' % (p[0], ('%g' % p[1]), ('%g' % p[2]), p[3]) for p in pills)
out.write_text(
    '// Generated by tools/make-wordmark.py from assets/logo-on-dark.webp. Do not edit by hand.\n'
    '// Each entry is [row, x0, x1, accent] in logo pixels: one pill per solid horizontal run.\n'
    'export const WORDMARK = {\n'
    '  width: %d, height: %d, top: %g, rows: %d, band: %g,\n'
    '  pills: [\n  %s\n  ],\n};\n' % (W, H, y0, ROWS, band, body)
)
print('rows', ROWS, 'pills', len(pills), 'accent', sum(p[3] for p in pills), 'bytes', out.stat().st_size)
